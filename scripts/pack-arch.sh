#!/usr/bin/env bash
# Build an Arch Linux package (.pkg.tar.zst) from the Linux .deb Tauri bundle.
# Runs on Arch (makepkg) or inside `archlinux` docker: root is re-execed as an
# unprivileged builder, because makepkg refuses to run as root.
#
# usage: pack-arch.sh <bundle-dir-with-deb> <version> [outdir]
set -euo pipefail

bundle="${1:?usage: pack-arch.sh <bundle-dir> <version> [outdir]}"
version="${2:?usage: pack-arch.sh <bundle-dir> <version> [outdir]}"
out="${3:-$(pwd)/out}"

# A dev build is `0.2.5-dev.22`, and makepkg refuses a hyphen in pkgver outright. The dots keep
# pacman's ordering honest: `0.2.5.dev.22` sorts before `0.2.5`, which is what a dev build is.
pkgver="${version//-/.}"

deb="$(find "$bundle" -name '*.deb' -type f | head -n 1)"
[ -n "$deb" ] || { echo "no .deb under $bundle" >&2; exit 1; }
mkdir -p "$out"
out="$(cd "$out" && pwd)"

work="${TMPDIR:-/tmp}/slag-arch/$version"
rm -rf "$work"
mkdir -p "$work"
cp "$deb" "$work/slag.deb"

cat > "$work/PKGBUILD" <<EOF
# Generated by scripts/pack-arch.sh: repackages the .deb bundle, no Rust build here.
pkgname=slag
pkgver=$pkgver
pkgrel=1
pkgdesc="Note-taking app for quick thoughts, tasks and articles"
arch=('x86_64')
url="https://github.com/wssdozh/slag-v2"
license=('MIT')
depends=('cairo' 'desktop-file-utils' 'gdk-pixbuf2' 'glib2' 'gtk3' 'hicolor-icon-theme'
         'libsoup3' 'pango' 'webkit2gtk-4.1' 'libayatana-appindicator' 'librsvg')
options=('!strip' '!debug')
install=slag.install
source=('slag.deb')
sha256sums=('SKIP')

package() {
  bsdtar -xf "\$srcdir/slag.deb" -C "\$srcdir"
  bsdtar -xf "\$srcdir"/data.tar.* -C "\$pkgdir"
}
EOF

cat > "$work/slag.install" <<'EOF'
post_install() {
  gtk-update-icon-cache -q -t -f usr/share/icons/hicolor 2>/dev/null || true
  update-desktop-database -q 2>/dev/null || true
}

post_upgrade() {
  post_install
}

post_remove() {
  gtk-update-icon-cache -q -t -f usr/share/icons/hicolor 2>/dev/null || true
  update-desktop-database -q 2>/dev/null || true
}
EOF

build() {
  cd "$work"
  makepkg -f --noconfirm --nodeps
  cp -f ./*.pkg.tar.zst "$out/"
}

if [ "$(id -u)" -eq 0 ]; then
  id builder >/dev/null 2>&1 || useradd -m builder
  chown -R builder:builder "$work" "$out"
  su -s /bin/bash builder -c "cd '$work' && makepkg -f --noconfirm --nodeps && cp -f ./*.pkg.tar.zst '$out/'"
else
  build
fi

ls -l "$out"/*.pkg.tar.zst
