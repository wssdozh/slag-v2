/**
 * Retrieves concise, verified UI and workflow guidance for requested topics.
 * Returns overview + available topic catalog when topics are empty or unrecognized.
 */
export function getAppGuideContent(topics: unknown): string {
  const requested = Array.isArray(topics)
    ? topics.filter((t): t is AppGuideTopic => typeof t === 'string' && t in GUIDE_SECTIONS)
    : [];

  const effectiveTopics: AppGuideTopic[] = requested.length > 0 ? requested : ['overview'];

  return effectiveTopics
    .map((topic) => {
      const section = GUIDE_SECTIONS[topic];
      return `### ${section.title}\n${section.content}`;
    })
    .join('\n\n---\n\n');
}
